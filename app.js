async function loadContent() {
  const embedded = document.querySelector("#contentData");
  let embeddedData = null;
  if (embedded?.textContent) {
    embeddedData = JSON.parse(embedded.textContent);
  }

  const cached = localStorage.getItem(CONTENT_CACHE_KEY);
  if (cached) {
    try {
      const cachedData = JSON.parse(cached);
      const cachedTime = Date.parse(cachedData.updatedAt || "") || 0;
      const embeddedTime = Date.parse(embeddedData?.updatedAt || "") || 0;
      if (embeddedData && embeddedTime > cachedTime) {
        localStorage.setItem(CONTENT_CACHE_KEY, JSON.stringify(embeddedData));
        return embeddedData;
      }
      return cachedData;
    } catch {}
  }

  if (embeddedData) {
    localStorage.setItem(CONTENT_CACHE_KEY, JSON.stringify(embeddedData));
    return embeddedData;
  }

  const response = await fetch("data/content.json", { cache: "no-store" });
  const data = await response.json();
  localStorage.setItem(CONTENT_CACHE_KEY, JSON.stringify(data));
  localStorage.setItem(CONTENT_REFRESH_KEY, String(Date.now()));
  return data;
}

async function refreshContentInBackground(force = false) {
  const last = Number(localStorage.getItem(CONTENT_REFRESH_KEY) || 0);
  if (!force && Date.now() - last < CONTENT_REFRESH_INTERVAL) return;
  setRefreshStatus("refreshStatusChecking");
  try {
    const response = await fetch(`data/content.json?ts=${Date.now()}`, { cache: "no-store" });
    const fresh = await response.json();
    if (!state.content || fresh.updatedAt !== state.content.updatedAt) {
      state.content = fresh;
      localStorage.setItem(CONTENT_CACHE_KEY, JSON.stringify(fresh));
      localStorage.setItem(CONTENT_REFRESH_KEY, String(Date.now()));
      renderAll();
      showToast(t("contentUpdated") || "Content updated");
    } else {
      localStorage.setItem(CONTENT_REFRESH_KEY, String(Date.now()));
      setRefreshStatus("refreshStatusFresh");
    }
  } catch (error) {
    console.error(error);
    setRefreshStatus("refreshStatusOffline");
  }
}

