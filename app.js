function pickMainBlocker(missingFc, missingRfc, tax) {
  if (missingRfc > 0) return t("blockerRefined");
  if (tax && (tax.fc > 0 || tax.rfc > 0)) return t("blockerPrereq");
  if (missingFc > 0) return t("blockerFireCrystal");
  return t("blockerReady");
}

function getEventReadiness(days, weeks, missingRfc) {
  const config = getPlannerModeConfig();
  const eventDays = Number(document.querySelector("#daysUntilEvent")?.value || config.eventWindowDays);
  const rfcDays = typeof weeks === "number" ? weeks * 7 : (missingRfc > 0 ? Infinity : 0);
  const waitDays = Math.max(Number(days || 0), rfcDays);
  if (waitDays <= eventDays) return t("eventReadyGood");
  if (waitDays <= eventDays + 7) return t("eventReadyRisk");
  return t("eventReadySave");
}

