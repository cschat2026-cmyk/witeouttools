function calculatePlanner(options = {}) {
  if (!state.content) return;
  updatePlannerModeButtons();
  const currentLevelInput = document.querySelector("#currentLevel");
  const targetLevelInput = document.querySelector("#targetLevel");
  const currentLevel = currentLevelInput.value;
  const targetLevel = targetLevelInput.value;
  const currentCrystals = Number(document.querySelector("#currentCrystals").value || 0);
  const currentRefined = Number(document.querySelector("#currentRefined").value || 0);
  const modeConfig = getPlannerModeConfig();
  const daily = Math.max(1, Number(document.querySelector("#dailyCrystals").value || 1)) * modeConfig.dailyMultiplier;
  const weeklyRefined = Math.max(0, Number(document.querySelector("#weeklyRefined").value || 0));
  const speedupHours = Number(document.querySelector("#speedupHours")?.value || 0);

  const rows = state.content.resourceDataLab?.furnaceRows || [];
  const startOrder = getFurnaceOrderByLevel(currentLevel);
  let targetOrder = getFurnaceOrderByLevel(targetLevel);
  if (startOrder > targetOrder) {
    targetOrder = startOrder;
    targetLevelInput.value = currentLevel;
  }
  const route = getRowsBetween(rows, startOrder, targetOrder);
  const totals = sumRows(route, ["fireCrystals", "refinedFireCrystals", "buildDays"]);
  const plannerTax = calculateBuildingTax(startOrder, targetOrder);
  const baseCrystalNeed = Number(totals.fireCrystals || 0) + plannerTax.fc;
  const baseRefinedNeed = Number(totals.refinedFireCrystals || 0) + plannerTax.rfc;
  const crystalNeed = Math.max(0, baseCrystalNeed - currentCrystals);
  const refinedNeed = Math.max(0, baseRefinedNeed - currentRefined);
  const resourceDays = Math.ceil(crystalNeed / daily);
  const buildDays = Math.max(0, Math.ceil(Number(totals.buildDays || 0) - speedupHours / 24));
  const days = Math.max(resourceDays, buildDays);
  const weeks = weeklyRefined > 0 ? Math.ceil(refinedNeed / weeklyRefined) : (refinedNeed > 0 ? "-" : 0);
  const nextStep = route[0] || rows.find((item) => item.order === targetOrder) || rows[0];

  document.querySelector("#missingCrystals").textContent = crystalNeed.toLocaleString();
  document.querySelector("#daysNeeded").textContent = Number.isFinite(days) ? days.toLocaleString() : "0";
  document.querySelector("#missingRefined").textContent = refinedNeed.toLocaleString();
  document.querySelector("#weeksNeeded").textContent = typeof weeks === "number" ? weeks.toLocaleString() : weeks;
  const mainBlocker = document.querySelector("#mainBlocker");
  const readiness = document.querySelector("#eventReadiness");
  if (mainBlocker) {
    const buildGapHours = Math.max(0, Number(totals.buildDays || 0) * 24 - speedupHours);
    mainBlocker.textContent = buildGapHours > 0 && crystalNeed === 0 && refinedNeed === 0 ? t("speedupGapLabel") : pickMainBlocker(crystalNeed, refinedNeed, plannerTax);
  }
  if (readiness) readiness.textContent = getEventReadiness(days, weeks, refinedNeed);
  const targetMeta = (state.content.fireCrystalLevels || []).find((item) => item.level === targetLevel.replace(/-.*/, ""));
  document.querySelector("#upgradePriority").textContent = localText(targetMeta?.priority) || (state.content.fireCrystalPlannerMeta?.notes?.[state.lang] || state.content.fireCrystalPlannerMeta?.notes?.en || "");
  document.querySelector("#plannerMilestone").textContent = t("plannerMilestoneTitle") + ": " + nextStep.level + " | " + Number(nextStep.fireCrystals || 0).toLocaleString(state.lang) + " FC" + (nextStep.refinedFireCrystals ? " | " + Number(nextStep.refinedFireCrystals).toLocaleString(state.lang) + " RFC" : "");
  document.querySelector("#plannerSources").textContent = t("plannerSourceTitle") + ": " + (state.content.resourceDataLab?.notes?.[state.lang] || state.content.fireCrystalPlannerMeta?.notes?.[state.lang] || state.content.fireCrystalPlannerMeta?.notes?.en || "");
  document.querySelector("#plannerRoute").innerHTML = '<span class="planner-route-title">' + t("plannerRouteTitle") + '</span>' + route.slice(0, 8).map((item) => {
    const rfc = item.refinedFireCrystals ? ' · ' + Number(item.refinedFireCrystals).toLocaleString(state.lang) + ' RFC' : '';
    return '<article class="route-step ' + (item.order === targetOrder ? 'active' : '') + '"><strong>' + item.level + '</strong><small>' + Number(item.fireCrystals || 0).toLocaleString(state.lang) + ' FC' + rfc + '</small></article>';
  }).join("");

  if (!options.skipResourceSync) syncResourceLabToPlanner({ silent: true });
  renderSmartPlanner();
  renderPlannerExecutionPanel();
  renderPlannerLinkedPanel();
  renderPlannerPrepPack();
  renderResourceJourneyPanel();
  renderShareBrief();
  renderHeroSnapshot();
  renderHeroPreviewStage();
  renderHeroActionRail();
  renderHubCards();
  renderMissionGrid();
  renderOpsBriefing();
  renderDailyCockpit();
  renderDecisionBoard();
  renderStatusStrip();
}


