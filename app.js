function persistCurrentMemory() {
  const memory = getUserMemory();
  MEMORY_FIELDS.forEach((id) => {
    const node = document.querySelector("#" + id);
    if (!node) return;
    memory[id] = readFieldValue(node);
  });
  memory.updatedAt = new Date().toISOString();
  localStorage.setItem(MEMORY_KEY, JSON.stringify(memory));
}

function bindMemoryInputs() {
  MEMORY_FIELDS.forEach((id) => {
    const node = document.querySelector("#" + id);
    if (!node || node.dataset.memoryBound === "1") return;
    const eventName = node.type === "checkbox" || node.tagName === "SELECT" ? "change" : "input";
    node.addEventListener(eventName, () => {
      writeUserMemory(id, readFieldValue(node));
      updateMemoryStatus();
    });
    node.dataset.memoryBound = "1";
  });
}

