function getRowsBetween(rows, startOrder, targetOrder) {
  const start = Number(startOrder || 0);
  const target = Math.max(Number(targetOrder || 0), start);
  return rows.filter((row) => row.order > start && row.order <= target);
}

function getBuildingCostRows(startOrder, targetOrder) {
  const lab = state.content?.resourceDataLab;
  const rows = [...(lab?.buildingCrystalCosts?.major || []), ...(lab?.buildingCrystalCosts?.late || [])];
  const startLabel = (lab?.furnaceRows || []).find((row) => row.order === Number(startOrder))?.level || "F30";
  const targetRows = getRowsBetween(lab?.furnaceRows || [], startOrder, targetOrder);
  const wantedMajorOrders = new Set();
  const wantedLateLabels = new Set();

  targetRows.forEach((row) => {
    if (/^FC[1-5]$/.test(row.level)) wantedMajorOrders.add(Number(row.level.replace("FC", "")));
    if (/^FC[5-9]-\d$/.test(row.level) || /^FC(6|7|8|9|10)$/.test(row.level)) wantedLateLabels.add(row.level);
  });

  return rows.filter((row) => {
    if (row.level.startsWith("FC") && row.level.includes("-")) return wantedLateLabels.has(row.level);
    if (/^FC(6|7|8|9|10)$/.test(row.level)) return wantedLateLabels.has(row.level);
    if (/^FC[1-5]$/.test(row.level)) return wantedMajorOrders.has(row.order) && startLabel !== row.level;
    return false;
  });
}

function calculateBuildingTax(startOrder, targetOrder) {
  const rows = getBuildingCostRows(startOrder, targetOrder);
  return rows.reduce((total, row) => {
    const embassy = row.embassy || {};
    const camp = row.camp || {};
    total.fc += Number(embassy.fc || 0) + Number(camp.fc || 0);
    total.rfc += Number(embassy.rfc || 0) + Number(camp.rfc || 0);
    if (Number(embassy.fc || 0) || Number(embassy.rfc || 0)) total.items.push(row.level + " Embassy");
    if (Number(camp.fc || 0) || Number(camp.rfc || 0)) total.items.push(row.level + " troop camp");
    return total;
  }, { fc: 0, rfc: 0, items: [] });
}

