function syncStateAgeLevelOptions() {
  const select = document.querySelector("#stateAgeCurrentLevel");
  const rows = state.content?.resourceDataLab?.furnaceRows || [];
  if (!select || !rows.length) return;
  const savedOrder = localStorage.getItem("wos-state-age-current-order");
  const plannerLevel = document.querySelector("#currentLevel")?.value || "F30";
  const plannerOrder = getFurnaceOrderByLevel(plannerLevel);
  const wanted = savedOrder || String(plannerOrder || 0);
  if (select.dataset.ready !== "1" || select.dataset.lang !== state.lang) {
    select.innerHTML = rows.map((row) => {
      const fc = Number(row.fireCrystals || 0).toLocaleString(state.lang);
      const rfc = row.refinedFireCrystals ? " / " + Number(row.refinedFireCrystals).toLocaleString(state.lang) + " RFC" : "";
      return '<option value="' + row.order + '">' + row.level + ' · ' + fc + ' FC' + rfc + '</option>';
    }).join("");
    select.dataset.ready = "1";
    select.dataset.lang = state.lang;
  }
  select.value = rows.some((row) => String(row.order) === String(wanted)) ? String(wanted) : String(plannerOrder || 0);
}

