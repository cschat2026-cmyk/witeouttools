function writeUserMemory(id, value) {
  const memory = getUserMemory();
  memory[id] = value;
  memory.updatedAt = new Date().toISOString();
  localStorage.setItem(MEMORY_KEY, JSON.stringify(memory));
}

function readFieldValue(node) {
  if (!node) return undefined;
  if (node.type === "checkbox") return node.checked ? "1" : "0";
  return node.value;
}

function setFieldValue(node, value) {
  if (!node || value === undefined || value === null) return;
  if (node.type === "checkbox") node.checked = value === true || value === "1" || value === "true";
  else node.value = String(value);
}

function restoreUserMemory() {
  if (state.restoredMemory) return;
  const memory = getUserMemory();
  if (memory.stateAgeCurrentLevel !== undefined) localStorage.setItem("wos-state-age-current-order", String(memory.stateAgeCurrentLevel));
  if (memory.plannerMode) localStorage.setItem("wos-planner-mode", String(memory.plannerMode));
  if (memory.activeRegion) {
    state.activeRegion = String(memory.activeRegion);
    localStorage.setItem("wos-region", state.activeRegion);
  }
  MEMORY_FIELDS.forEach((id) => {
    const node = document.querySelector("#" + id);
    if (!node || memory[id] === undefined) return;
    setFieldValue(node, memory[id]);
  });
  const savedPlayerId = localStorage.getItem("wos-player-id");
  if (savedPlayerId && !document.querySelector("#playerIdInput")?.value) setFieldValue(document.querySelector("#playerIdInput"), savedPlayerId);
  state.restoredMemory = true;
}

function persistCurrentMemory() {
  const memory = getUserMemory();
  MEMORY_FIELDS.forEach((id) => {
    const node = document.querySelector("#" + id);
    if (!node) return;
    memory[id] = readFieldValue(node);
  });
  memory.updatedAt = new Date().toISOString();
  localStorage.setItem(MEMORY_KEY, JSON.stringify(memory));
}

function bindMemoryInputs() {
  MEMORY_FIELDS.forEach((id) => {
    const node = document.querySelector("#" + id);
    if (!node || node.dataset.memoryBound === "1") return;
    const eventName = node.type === "checkbox" || node.tagName === "SELECT" ? "change" : "input";
    node.addEventListener(eventName, () => {
      writeUserMemory(id, readFieldValue(node));
      updateMemoryStatus();
    });
    node.dataset.memoryBound = "1";
  });
}

function updateMemoryStatus() {
  const nodes = document.querySelectorAll("[data-memory-status]");
  if (!nodes.length) return;
  const memory = getUserMemory();
  const savedAt = memory.updatedAt ? new Date(memory.updatedAt) : null;
  const suffix = savedAt && !Number.isNaN(savedAt.getTime())
    ? " · " + savedAt.toLocaleTimeString(state.lang, { hour: "2-digit", minute: "2-digit" })
    : "";
  nodes.forEach((node) => {
    node.textContent = t("memorySavedHint") + suffix;
  });
}

