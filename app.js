function persistTimerState(isRunning = Boolean(state.timerId)) {
  localStorage.setItem(TIMER_STATE_KEY, JSON.stringify({
    timerSeconds: state.timerSeconds,
    savedAt: Date.now(),
    isRunning
  }));
}

function restoreTimerState() {
  try {
    const saved = JSON.parse(localStorage.getItem(TIMER_STATE_KEY) || "null");
    if (!saved) return;
    const elapsed = saved.isRunning ? Math.floor((Date.now() - Number(saved.savedAt || Date.now())) / 1000) : 0;
    state.timerSeconds = Math.max(0, Math.min(1800, Number(saved.timerSeconds || 1800) - elapsed));
  } catch {
    state.timerSeconds = 1800;
  }
}

function startTimer() {
  if (state.timerId) return;
  persistTimerState(true);
  state.timerId = window.setInterval(() => {
    state.timerSeconds = Math.max(0, state.timerSeconds - 1);
    persistTimerState(true);
    renderTimer();
    if (state.timerSeconds === 0) pauseTimer();
  }, 1000);
}

function pauseTimer() {
  window.clearInterval(state.timerId);
  state.timerId = null;
  persistTimerState(false);
}

function resetTimer() {
  pauseTimer();
  state.timerSeconds = 1800;
  persistTimerState(false);
  renderTimer();
}

function renderTimer() {
  const minutes = String(Math.floor(state.timerSeconds / 60)).padStart(2, "0");
  const seconds = String(state.timerSeconds % 60).padStart(2, "0");
  document.querySelector("#timerDisplay").textContent = `${minutes}:${seconds}`;
  const elapsed = 1800 - state.timerSeconds;
  let phase = "ready";
  if (elapsed > 0 && elapsed < 600) phase = "open";
  if (elapsed >= 600 && elapsed < 1320) phase = "fight";
  if (elapsed >= 1320) phase = "close";
  const phaseKey = phase === "ready" ? "Ready" : phase[0].toUpperCase() + phase.slice(1);
  document.querySelector("#phaseLabel").textContent = t(`phase${phaseKey}`);
  document.querySelector("#phaseAdvice").textContent = t(`phase${phaseKey}Advice`);
  renderBattleBoard(phase, elapsed);
  renderFrostfireTimeline(elapsed);
  const checklist = phase === "ready" ? checklistByPhase.open[state.lang] : checklistByPhase[phase][state.lang];
  document.querySelector("#eventChecklist").innerHTML = checklist.map((item, index) => `
    <label class="check-item">
      <input type="checkbox" data-check="${phase}-${index}" ${localStorage.getItem(`wos-check-${phase}-${index}`) === "1" ? "checked" : ""} />
      <span>${item}</span>
    </label>
  `).join("");
  document.querySelectorAll("[data-check]").forEach((input) => {
    input.addEventListener("change", () => {
      localStorage.setItem(`wos-check-${input.dataset.check}`, input.checked ? "1" : "0");
    });
  });
}

function renderBattleBoard(phase, elapsedSeconds) {
  const root = document.querySelector("#battleBoard");
  if (!root || !state.content) return;

  const commands = state.content.frostfireCommands?.[phase] || state.content.frostfireCommands?.ready;
  const timeline = state.content.frostfireTimeline || [];
  const elapsedMinute = elapsedSeconds / 60;
  const nextMilestone = timeline.find((item) => item.minute > elapsedMinute) || null;
  const doNow = commands?.doNow?.[state.lang] || commands?.doNow?.en || [];
  const objective = commands?.objective?.[state.lang] || commands?.objective?.en || "";
  const nextPrep = commands?.nextPrep?.[state.lang] || commands?.nextPrep?.en || "";
  const avoid = commands?.avoid?.[state.lang] || commands?.avoid?.en || "";
  const minutesAway = nextMilestone ? Math.max(0, Math.ceil(nextMilestone.minute - elapsedMinute)) : 0;

  const nextWindowMarkup = nextMilestone
    ? `
      <div class="battle-window-meta">
        <span>${t("timerCommandIn")} ${minutesAway} ${t("minuteShort")}</span>
        <strong>${nextMilestone.label[state.lang]}</strong>
      </div>
      <p>${nextMilestone.advice[state.lang]}</p>
    `
    : `<p>${nextPrep}</p>`;

  root.innerHTML = `
    <div class="battle-board-head">
      <span>${t("timerCommandTitle")}</span>
      <strong>${t(`phase${phase === "ready" ? "Ready" : phase[0].toUpperCase() + phase.slice(1)}`)}</strong>
    </div>
    <div class="battle-grid">
      <article class="battle-card battle-card-objective">
        <span>${t("timerCommandObjective")}</span>
        <strong>${objective}</strong>
      </article>
      <article class="battle-card">
        <span>${t("timerCommandNow")}</span>
        <ul class="battle-list">
          ${doNow.map((item) => `<li>${item}</li>`).join("")}
        </ul>
      </article>
      <article class="battle-card">
        <span>${t("timerCommandNext")}</span>
        ${nextWindowMarkup}
      </article>
      <article class="battle-card battle-card-avoid">
        <span>${t("timerCommandAvoid")}</span>
        <p>${avoid}</p>
      </article>
    </div>
  `;
}

function renderFrostfireTimeline(elapsedSeconds) {
  const timeline = state.content?.frostfireTimeline || [];
  const elapsedMinute = elapsedSeconds / 60;
  let currentIndex = 0;
  timeline.forEach((item, index) => {
    if (item.minute <= elapsedMinute) currentIndex = index;
  });
  const next = timeline.find((item) => item.minute >= elapsedMinute) || null;
  const active = next && Math.abs(next.minute - elapsedMinute) < 1 ? next : null;

  document.querySelector("#nextWindow").innerHTML = next ? `
    <span>${t("nextWindowLabel")}</span>
    <strong>${active ? t("nextWindowNow") : `${Math.ceil(next.minute - elapsedMinute)} ${t("minuteShort")}`}: ${next.label[state.lang]}</strong>
    <small>${next.advice[state.lang]}</small>
  ` : `
    <span>${t("nextWindowLabel")}</span>
    <strong>${t("nextWindowDone")}</strong>
    <small>${timeline.at(-1)?.advice[state.lang] || ""}</small>
  `;

  renderShareBrief();
  document.querySelector("#frostfireTimeline").innerHTML = timeline.map((item, index) => {
    const status = index < currentIndex ? "past" : index === currentIndex ? "active" : "";
    return `
      <article class="timeline-item ${status} ${item.type} searchable" data-search="${item.label[state.lang]} ${item.advice[state.lang]} ${item.minute}">
        <span>${String(item.minute).padStart(2, "0")}:00</span>
        <strong>${item.label[state.lang]}</strong>
        <small>${item.advice[state.lang]}</small>
      </article>
    `;
  }).join("");
}

function setRegion(region) {
  state.activeRegion = region;
  if (localStorage.getItem("wos-region") !== region) localStorage.setItem("wos-region", region);
  if (getUserMemory().activeRegion !== region) writeUserMemory("activeRegion", region);
  document.querySelectorAll("[data-region]").forEach((button) => {
    button.classList.toggle("active", button.dataset.region === region);
  });
  document.querySelector("#regionNotes").value = localStorage.getItem(`wos-region-note-${region}`) || "";
}

function saveRegionNote() {
  const value = document.querySelector("#regionNotes").value;
  localStorage.setItem(`wos-region-note-${state.activeRegion}`, value);
  writeUserMemory("regionNotes-" + state.activeRegion, value);
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const input = document.createElement("textarea");
    input.value = text;
    input.setAttribute("readonly", "");
    input.style.position = "fixed";
    input.style.left = "-9999px";
    document.body.appendChild(input);
    input.select();
    document.execCommand("copy");
    input.remove();
  }
  showToast(`${t("copied")}: ${text}`);
}

function showToast(message) {
  const toast = document.querySelector("#toast");
  toast.textContent = message;
  toast.classList.add("show");
  window.clearTimeout(showToast.timeout);
  showToast.timeout = window.setTimeout(() => toast.classList.remove("show"), 1800);
}

function runSearch() {
  const query = document.querySelector("#siteSearch").value.trim().toLowerCase();
  let visible = 0;
  document.querySelectorAll(".searchable").forEach((node) => {
    const match = !query || node.dataset.search.toLowerCase().includes(query);
    node.classList.toggle("hidden", !match);
    if (match) visible += 1;
  });
  if (query && visible === 0) showToast(t("noResults"));
}

