function getLocalDateKey(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return year + "-" + month + "-" + day;
}

function getDailyDoneKey(index) {
  return DAILY_DONE_PREFIX + "-" + getLocalDateKey() + "-" + index;
}

function setDailyTaskDone(index, done) {
  const key = getDailyDoneKey(index);
  if (done) localStorage.setItem(key, "1");
  else localStorage.removeItem(key);
  renderOpsBriefing();
}

function isDailyTaskDone(index) {
  return localStorage.getItem(getDailyDoneKey(index)) === "1";
}

function getDailyActionTarget(task) {
  if (task.type === "copy-share") return "share";
  return task.action || "codes";
}

function runDailyTask(task, index) {
  if (task.type === "copy-share") copyText(buildShareBrief());
  else {
    const target = document.querySelector("#" + getDailyActionTarget(task));
    if (target) target.scrollIntoView({ behavior: "smooth", block: "start" });
  }
  setDailyTaskDone(index, true);
}

function renderDailyTaskBoard() {
  const tasks = translations[state.lang].dailyTasks || [];
  if (!tasks.length) return "";
  return [
    '<div class="daily-task-board">',
    '<span class="ops-briefing-label">' + t("dailyBoardTitle") + '</span>',
    tasks.map((task, index) => {
      const done = isDailyTaskDone(index);
      const actionLabel = task.type === "copy-share" ? t("dailyActionCopy") : t("dailyActionGo");
      return [
        '<article class="daily-task ' + (done ? "done" : "") + '">',
        '<label>',
        '<input type="checkbox" data-daily-done="' + index + '" ' + (done ? "checked" : "") + ' />',
        '<span><strong>' + task.title + '</strong><small>' + task.note + '</small></span>',
        '</label>',
        '<button class="button secondary" type="button" data-daily-action="' + index + '">' + (done ? t("dailyActionDone") : actionLabel) + '</button>',
        '</article>'
      ].join("");
    }).join(""),
    '</div>'
  ].join("");
}



