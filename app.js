function getAdConfig() {
  const runtime = window.__WHITEOUT_ADS__ || {};
  return {
    provider: runtime.provider || DEFAULT_AD_CONFIG.provider,
    ezoic: {
      ...DEFAULT_AD_CONFIG.ezoic,
      ...(runtime.ezoic || {}),
      placements: {
        ...DEFAULT_AD_CONFIG.ezoic.placements,
        ...((runtime.ezoic && runtime.ezoic.placements) || {})
      }
    },
    adsense: {
      ...DEFAULT_AD_CONFIG.adsense,
      ...(runtime.adsense || {}),
      slots: {
        ...DEFAULT_AD_CONFIG.adsense.slots,
        ...((runtime.adsense && runtime.adsense.slots) || {})
      }
    }
  };
}

function hasAdsenseConfig(config = getAdConfig()) {
  return Boolean(config.adsense?.enabled) && /^ca-pub-\d{10,}$/.test(config.adsense?.publisherId || "");
}

function hasAdsenseLiveSlots(config = getAdConfig()) {
  if (!hasAdsenseConfig(config)) return false;
  return Object.values(config.adsense?.slots || {}).some((value) => String(value || "").trim().length > 0);
}

function hasEzoicConfig(config = getAdConfig()) {
  const siteIdReady = String(config.ezoic?.siteId || "").trim().length > 0;
  const verificationReady = String(config.ezoic?.verificationMeta || "").trim() && String(config.ezoic?.verificationMeta || "").trim() !== "pending";
  const placementReady = Object.values(config.ezoic?.placements || {}).some((value) => String(value || "").trim().length > 0);
  return siteIdReady || verificationReady || placementReady;
}

function isEzoicEnabled(config = getAdConfig()) {
  return Boolean(config.ezoic?.enabled) && hasEzoicConfig(config);
}

function isEzoicActive(config = getAdConfig()) {
  if (!isEzoicEnabled(config)) return false;
  if ((window.ezstandalone && Array.isArray(window.ezstandalone.cmd)) || window.ezoicpubads || window.ezslots) return true;
  if (document.querySelector('script[src*="ezoic"], script[src*="ezstandalone"]')) return true;
  return false;
}

function ensureAdsenseScript(config = getAdConfig()) {
  if (!hasAdsenseLiveSlots(config) || document.querySelector("#adsenseScript")) return;
  const script = document.createElement("script");
  script.id = "adsenseScript";
  script.async = true;
  script.crossOrigin = "anonymous";
  script.src = "https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=" + config.adsense.publisherId;
  document.head.appendChild(script);
}

function ensureEzoicMeta(config = getAdConfig()) {
  const meta = document.querySelector('meta[name="ezoic-site-verification"]');
  if (!meta) return;
  meta.content = config.ezoic?.verificationMeta || "pending";
}

function ensureEzoicScript(config = getAdConfig()) {
  ensureEzoicMeta(config);
  if (!isEzoicEnabled(config)) return;
  if (config.ezoic?.siteId && window._ezoic && typeof window._ezoic.setSiteId === "function") {
    try {
      window._ezoic.setSiteId(config.ezoic.siteId);
    } catch {}
  }
}

